-- Each active SSE reserves worst-case tokens; expired leases recover after a process crash.
CREATE TABLE IF NOT EXISTS t_chat_request (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES t_user(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('active','closed')),
    reserved_tokens INTEGER NOT NULL DEFAULT 0,
    embedding_tokens INTEGER NOT NULL DEFAULT 0,
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    estimated_cost NUMERIC(18,8) NOT NULL DEFAULT 0,
    outcome VARCHAR(16),
    started_at TIMESTAMP NOT NULL DEFAULT clock_timestamp(),
    lease_until TIMESTAMP,
    ended_at TIMESTAMP,
    CHECK (reserved_tokens >= 0 AND embedding_tokens >= 0 AND input_tokens >= 0 AND output_tokens >= 0)
);
CREATE INDEX IF NOT EXISTS idx_chat_request_user_started ON t_chat_request(user_id,started_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_request_active ON t_chat_request(lease_until) WHERE status='active';
-- A conversation is bound to one user and one concrete published file version.
-- Only completed turns are stored; a request lease prevents concurrent turns
-- from reading the same stale history and recovers after a crashed API process.
CREATE TABLE IF NOT EXISTS t_chat_conversation (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES t_user(id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES t_ai_customer_service_md_storage(id) ON DELETE CASCADE,
    active_request_id UUID,
    lease_until TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMP NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMP NOT NULL,
    CHECK ((active_request_id IS NULL) = (lease_until IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_chat_conversation_user_recent ON t_chat_conversation(user_id,updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_conversation_expiry ON t_chat_conversation(expires_at);
CREATE TABLE IF NOT EXISTS t_chat_turn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES t_chat_conversation(id) ON DELETE CASCADE,
    request_id UUID NOT NULL UNIQUE,
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    sources JSON NOT NULL DEFAULT '[]',
    created_at TIMESTAMP NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS idx_chat_turn_recent ON t_chat_turn(conversation_id,id DESC);
ALTER TABLE t_chat_turn ADD COLUMN IF NOT EXISTS evidence_snapshot JSON;
-- Feedback copies its evidence independently of the 30-day conversation retention.
CREATE TABLE IF NOT EXISTS t_answer_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES t_user(id) ON DELETE CASCADE,
    request_id UUID NOT NULL,
    file_id BIGINT REFERENCES t_ai_customer_service_md_storage(id) ON DELETE SET NULL,
    category VARCHAR(32) NOT NULL,
    user_note TEXT NOT NULL DEFAULT '',
