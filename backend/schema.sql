    diagnosis VARCHAR(24) NOT NULL DEFAULT 'unknown',
    resolution VARCHAR(24), resolution_note TEXT,
    revision INTEGER NOT NULL DEFAULT 1,
    case_id BIGINT REFERENCES t_release_eval_case(id) ON DELETE SET NULL,
    regression_file_id BIGINT REFERENCES t_ai_customer_service_md_storage(id) ON DELETE SET NULL,
    report_id UUID REFERENCES t_release_eval_run(id) ON DELETE SET NULL,
    closure_evidence JSON,
    created_at TIMESTAMP NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMP NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(user_id,request_id)
);
CREATE INDEX IF NOT EXISTS idx_feedback_file_status ON t_answer_feedback(file_id,status,updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedback_user_recent ON t_answer_feedback(user_id,created_at DESC);
