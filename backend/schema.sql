-- Upload sessions survive process restarts. Chunks are stored on the same durable volume.
CREATE TABLE IF NOT EXISTS t_upload_session (
    id UUID PRIMARY KEY,
    original_file_name VARCHAR(200) NOT NULL,
    file_size BIGINT NOT NULL CHECK (file_size > 0),
    content_sha256 VARCHAR(64) NOT NULL,
    chunk_size INTEGER NOT NULL CHECK (chunk_size > 0),
    chunk_count INTEGER NOT NULL CHECK (chunk_count > 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('uploading', 'completed', 'expired')),
    file_id BIGINT,
    create_time TIMESTAMP NOT NULL,
    update_time TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_upload_resume
    ON t_upload_session (content_sha256, file_size, status, expires_at);
ALTER TABLE t_upload_session ADD COLUMN IF NOT EXISTS owner_id BIGINT REFERENCES t_user(id);
CREATE TABLE IF NOT EXISTS t_upload_chunk (
    upload_id UUID NOT NULL REFERENCES t_upload_session(id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    chunk_size INTEGER NOT NULL CHECK (chunk_size > 0),
    chunk_sha256 VARCHAR(64) NOT NULL,
    PRIMARY KEY (upload_id, chunk_index)
);

